// Report the body plan assigned to every record, for review.
//
//   node scripts/build-body-plan-report.mjs
//
// The body plan decides which hit locations a monster has in Foundry, and it is
// derived from the creature's stated limbs rather than declared anywhere. That
// makes it exactly the kind of thing that should be looked at by a person once
// instead of trusted 304 times, so the derivation writes down what it decided
// and what it decided it from. Anything wrong here is corrected by naming the
// record in schema/foundry-body-plans.json, not by tuning the derivation until
// one creature comes out right and three others quietly change.

import { readFileSync, writeFileSync } from "node:fs";
import { HIT_LOCATION_PLANS, bodyPlan } from "./foundry-module.mjs";

const PACKAGE_PATH = "converted/doa-monsters.json";
const OVERRIDES_PATH = "schema/foundry-body-plans.json";
const OUT_PATH = "review/reports/foundry-body-plans.md";

const pkg = JSON.parse(readFileSync(PACKAGE_PATH, "utf8"));
const overrides = JSON.parse(readFileSync(OVERRIDES_PATH, "utf8")).overrides;

/** The trait fragments the derivation actually reads, so a reviewer sees its evidence. */
function evidence(monster) {
  const interesting = /Legs|Extra Arms|Extra-Flexible Long .*Arms|Flight/i;
  const found = (monster.stats?.traits ?? []).filter(trait => interesting.test(trait));
  return found.length > 0 ? found.join("; ") : "—";
}

const rows = pkg.monsters.map(monster => ({
  name: monster.name,
  id: monster.id,
  plan: bodyPlan(monster),
  overridden: Boolean(overrides[monster.id]),
  evidence: evidence(monster),
}));

const byPlan = new Map();
for (const row of rows) byPlan.set(row.plan, (byPlan.get(row.plan) ?? 0) + 1);

const lines = [
  "# Foundry Body Plans",
  "",
  "<!-- Generated by scripts/build-body-plan-report.mjs. Do not edit by hand. -->",
  "",
  "Which hit location table each record gets in the Foundry module. Derived from the limbs the",
  "record's own traits state; see `bodyPlan` in scripts/foundry-module.mjs. Rows marked ✓ in the",
  "Set column are named explicitly in [schema/foundry-body-plans.json](../../schema/foundry-body-plans.json)",
  "because their traits do not distinguish the plan.",
  "",
  "| Body plan | Records | Hit locations |",
  "| --- | ---: | ---: |",
  ...[...byPlan.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([plan, count]) => `| ${plan} | ${count} | ${HIT_LOCATION_PLANS[plan].length} |`),
  "",
  "## Every record",
  "",
  "| Monster | Body plan | Set | Stated limbs |",
  "| --- | --- | :-: | --- |",
  ...rows
    .slice()
    .sort((a, b) => a.plan.localeCompare(b.plan) || a.name.localeCompare(b.name))
    .map(row => `| ${row.name} | ${row.plan} | ${row.overridden ? "✓" : ""} | ${row.evidence} |`),
  "",
];

writeFileSync(OUT_PATH, `${lines.join("\n")}\n`, "utf8");
console.log(`Wrote ${OUT_PATH}: ${rows.length} record(s) across ${byPlan.size} body plan(s), `
  + `${rows.filter(row => row.overridden).length} set explicitly.`);
