// Authoring support for DOA-authored monster descriptions.
//
//   node scripts/build-descriptions.mjs             # coverage report
//   node scripts/build-descriptions.mjs --draft     # seed material for undescribed records
//   node scripts/build-descriptions.mjs --check     # fail on an invalid or stale content file
//
// The descriptions themselves are written by a person and tracked in
// content/descriptions/. This script never writes prose. It answers "which
// records still need one" and "what does the project already own that describes
// this creature", so authoring is a reading-and-writing job rather than an
// archaeology job.
//
// Seed material comes from art/enraged-eggplant/image-manifest.json, which
// records the exact prompt used for every generated asset. Those prompts are
// project-authored: they were written from each record's converted statistics,
// and none of them came from an SRD. That makes them a safe basis for CC BY
// prose in a way that SRD flavour text is not.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import {
  DESCRIPTIONS_PATH,
  descriptionsByRecord,
  loadDescriptionFile,
  validateDescriptionFile,
} from "./review/descriptions.mjs";

const BASE_PATH = "converted/enraged-eggplant/doa-monsters.review-required.json";
const REVIEWED_PATH = "converted/enraged-eggplant/doa-monsters.reviewed.json";
const ART_MANIFEST_PATH = "art/enraged-eggplant/image-manifest.json";
const REPORT_PATH = "review/reports/description-coverage.md";
const DRAFT_PATH = "review/reports/description-draft.md";

const args = process.argv.slice(2);
const draft = args.includes("--draft");
const check = args.includes("--check");
const limit = numberFor("--limit") ?? Infinity;
const outPath = valueFor("--out") ?? (draft ? DRAFT_PATH : REPORT_PATH);

const records = loadRecords();
const promptsById = loadPrompts();
const file = loadDescriptionFile(".");
const byRecord = descriptionsByRecord(file);

const knownIds = new Set(records.map(record => record.id));
const unknown = [...byRecord.keys()].filter(id => !knownIds.has(id));
if (unknown.length > 0) {
  console.error(`${DESCRIPTIONS_PATH} targets unknown record id(s): ${unknown.join(", ")}`);
  process.exit(1);
}

const rows = records.map(record => ({
  record,
  entry: byRecord.get(record.id) ?? null,
  seed: seedFor(record),
}));

if (check) {
  const errors = file ? validateDescriptionFile(file) : [`${DESCRIPTIONS_PATH} is missing`];
  if (errors.length > 0) {
    console.error(`${DESCRIPTIONS_PATH} is invalid:\n${errors.join("\n")}`);
    process.exit(1);
  }
  const described = rows.filter(row => row.entry).length;
  console.log(`${DESCRIPTIONS_PATH} is valid: ${described}/${rows.length} record(s) described.`);
  process.exit(0);
}

const text = draft ? renderDraft(rows) : renderReport(rows);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, text, "utf8");
console.log(`Wrote ${outPath}.`);

function renderReport(allRows) {
  const described = allRows.filter(row => row.entry);
  const remaining = allRows.filter(row => !row.entry);
  const lengths = described.map(row => row.entry.text.length).sort((a, b) => a - b);
  const byTier = new Map();
  for (const row of remaining) {
    const tier = row.seed.tier;
    byTier.set(tier, (byTier.get(tier) ?? 0) + 1);
  }

  const lines = [
    "# Monster description coverage",
    "",
    "Generated by `npm run descriptions:report`. Do not edit by hand.",
    "",
    `Descriptions are original Dungeons on Automatic prose. See [description policy](../policy/description-policy.md)`,
    "for why they are authored rather than imported, and what a description may be written from.",
    "",
    "## Coverage",
    "",
    "| | Records |",
    "| --- | ---: |",
    `| Described | ${described.length} |`,
    `| Not yet described | ${remaining.length} |`,
    `| Total | ${allRows.length} |`,
    "",
  ];

  if (lengths.length > 0) {
    const median = lengths[Math.floor(lengths.length / 2)];
    lines.push(
      "Authored text runs "
      + `${lengths[0]}-${lengths[lengths.length - 1]} characters, median ${median}.`,
      "",
    );
  }

  lines.push(
    "## Seed material available for the remaining records",
    "",
    "Every record has project-authored art direction behind it, but not in equal detail. The tier says how much",
    "descriptive prose already exists for the creature, which is a fair proxy for how long each one takes to write.",
    "",
    "| Seed tier | Records | What the project already has |",
    "| --- | ---: | --- |",
    `| authored-portrait | ${byTier.get("authored-portrait") ?? 0} | A hand-written scene sentence in the portrait prompt. |`,
    `| authored-token | ${byTier.get("authored-token") ?? 0} | A hand-written anatomy clause in the token prompt. |`,
    `| curated-cues | ${byTier.get("curated-cues") ?? 0} | Curated anatomical cue prose derived from the record. |`,
    `| record-only | ${byTier.get("record-only") ?? 0} | Raw trait and attack names; the prose starts from the statistics. |`,
    "",
  );

  if (remaining.length > 0) {
    lines.push(
      "## Not yet described",
      "",
      "| Record | Monster | Class | Seed tier |",
      "| --- | --- | --- | --- |",
      ...remaining.map(row =>
        `| \`${row.record.id}\` | ${row.record.name} | ${row.record.class ?? "-"} | ${row.seed.tier} |`),
      "",
    );
  }

  return `${lines.join("\n")}\n`;
}

function renderDraft(allRows) {
  const remaining = allRows.filter(row => !row.entry).slice(0, limit === Infinity ? undefined : limit);
  const lines = [
    "# Description drafting sheet",
    "",
    "Generated by `npm run descriptions:draft`. Working material, not a deliverable.",
    "",
    `${remaining.length} record(s) without an authored description. For each one the seed is what this project`,
    "already wrote about the creature, plus the statistics the prose has to stay true to. Turn it into two or three",
    "sentences of reader-facing prose and add the entry to `content/descriptions/enraged-eggplant.json`.",
    "",
    "Rules the validator enforces: single paragraph, 80-600 characters, no image-prompt phrasing",
    "(no \"three-quarter\", \"silhouette\", \"Depict\", \"crop-safe\"), and a `basis` naming what it was written from.",
    "",
  ];

  for (const row of remaining) {
    const { record, seed } = row;
    lines.push(
      `## ${record.name}`,
      "",
      `- id: \`${record.id}\``,
      `- class: ${record.class ?? "-"} | size: ${record.size?.hexes ?? "-"} | tier: ${record.effectiveness?.threatTier ?? "-"}`,
      `- seed tier: ${seed.tier}`,
      "",
    );
    if (seed.text) lines.push("Seed:", "", `> ${seed.text}`, "");
    const traits = (record.stats?.traits ?? []).slice(0, 14).join("; ");
    if (traits) lines.push(`Traits: ${traits}`, "");
    const attacks = (record.stats?.attacks ?? []).map(attack => attack.name).filter(Boolean).join(", ");
    if (attacks) lines.push(`Attacks: ${attacks}`, "");
    const notes = (record.stats?.notes ?? []).filter(note => /^Size |Weight /.test(note)).join(" ");
    if (notes) lines.push(`Scale: ${notes}`, "");
  }

  return `${lines.join("\n")}\n`;
}

/**
 * Pull the descriptive clause a person actually wrote for this creature out of
 * its art prompts. Portrait scene sentences are the richest, then token anatomy
 * clauses, then the curated cue lists; a record with none of those falls back to
 * its own statistics.
 */
function seedFor(record) {
  const prompts = promptsById.get(record.id);
  if (!prompts) return { tier: "record-only", text: null };

  const depict = /\bDepict ([^.]+\.)/.exec(prompts.portrait ?? "");
  if (depict) return { tier: "authored-portrait", text: depict[1].trim() };

  const anatomy = /\bIts anatomy is exact: ([^.]+\.)/.exec(prompts.portrait ?? "");
  if (anatomy) return { tier: "authored-portrait", text: anatomy[1].trim() };

  const subject = /\bSubject: ([^.]+\.)/.exec(prompts.token ?? "");
  if (subject) return { tier: "authored-token", text: subject[1].trim() };

  const cues = /Distinctive anatomical cues from the game record: ([a-z][^.]+\.)/.exec(prompts.portrait ?? "");
  if (cues) return { tier: "curated-cues", text: cues[1].trim() };

  return { tier: "record-only", text: null };
}

function loadRecords() {
  for (const path of [BASE_PATH, REVIEWED_PATH]) {
    try {
      return JSON.parse(readFileSync(path, "utf8")).monsters;
    } catch {
      continue;
    }
  }
  console.error(`Could not read ${BASE_PATH} or ${REVIEWED_PATH}.`);
  process.exit(1);
}

function loadPrompts() {
  const manifest = JSON.parse(readFileSync(ART_MANIFEST_PATH, "utf8"));
  return new Map(manifest.records.map(record => [record.monsterId, {
    portrait: record.assets?.portrait?.prompt ?? "",
    token: record.assets?.token?.prompt ?? "",
  }]));
}

function valueFor(name) {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : undefined;
}

function numberFor(name) {
  const value = valueFor(name);
  if (value === undefined) return undefined;
  const parsed = Number.parseInt(value, 10);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : undefined;
}
