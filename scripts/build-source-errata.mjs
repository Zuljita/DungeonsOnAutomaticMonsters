// Collect the source errata worth reporting back to Enraged Eggplant.
//
//   node scripts/build-source-errata.mjs
//
// Two classes of finding, both mechanical and both checkable by the author
// against their own document:
//
//   1. Trait costs that do not follow from the construction the document itself
//      writes down — a stated cost pricing a different number of levels, or a
//      different modifier total, than the listed trait. Detected by the library
//      adjudication pass and already adopted in the DOA rebuild.
//
//   2. Typical Stats Dodge values that do not follow from the same block's Basic
//      Speed and the creature's own listed traits. Detected by having GCS
//      evaluate the rebuilt sheet, which is the same engine the author's own
//      files run through.
//
// This is an errata report, not a correction log: it says what does not add up,
// with the arithmetic shown, so the author can decide what was intended.

import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { REVIEWED_PATH } from "./review/build-candidate.mjs";
import { convertInPlace } from "./gcs-cli.mjs";

const SHEET_DIR = "converted/enraged-eggplant/gcs-sheets";
const AUDIT_PATH = "converted/enraged-eggplant/library-audit.json";
const OUT_PATH = "review/reports/source-errata.md";

const pkg = JSON.parse(readFileSync(REVIEWED_PATH, "utf8"));
const audit = JSON.parse(readFileSync(AUDIT_PATH, "utf8"));

// --- 1. cost discrepancies -------------------------------------------------

const costs = [];
for (const monster of audit.monsters ?? []) {
  for (const match of monster.matches ?? []) {
    if (!match.difference) continue;
    costs.push({
      monster: monster.name,
      construction: match.source_text,
      stated: match.source_points,
      library: match.library_points,
    });
  }
}
costs.sort((a, b) => a.monster.localeCompare(b.monster));

// --- 2. dodge that does not follow from the block's own numbers ------------

const scratch = mkdtempSync(join(tmpdir(), "doa-errata-"));
cpSync(SHEET_DIR, scratch, { recursive: true });
convertInPlace(scratch);

const dodges = [];
for (const record of pkg.monsters) {
  const stated = record.stats?.attributes?.dodge;
  if (stated == null) continue;
  const resolved = JSON.parse(readFileSync(join(scratch, `${record.id}.gcs`), "utf8"));
  const computed = Number(resolved.calc?.dodge?.[0]);
  if (computed === Number(stated)) continue;
  const speed = resolved.attributes.find(entry => entry.attr_id === "basic_speed")?.calc?.value;
  // Everything above Basic Speed + 3 comes from the creature's own listed traits.
  const bonus = computed - (Math.floor(speed) + 3);
  dodges.push({
    monster: record.name,
    speed,
    stated,
    computed,
    bonus,
    difference: Number(stated) - computed,
  });
}
rmSync(scratch, { recursive: true, force: true });
dodges.sort((a, b) => a.monster.localeCompare(b.monster));

// --- report ----------------------------------------------------------------

const lines = [
  "# Source Errata for Enraged Eggplant",
  "",
  "<!-- Generated by scripts/build-source-errata.mjs. Do not edit by hand. -->",
  "",
  "Original GURPS conversion by Enraged Eggplant, from Monsters (May 11, 2024); adapted and",
  "republished with permission. These are the places where the document disagrees with its own",
  "arithmetic, gathered so they can be corrected at the source rather than only downstream.",
  "",
  "Both lists cover only the 304 SRD-overlap monsters Dungeons on Automatic rebuilt. Neither is a",
  "judgement about the design — only about whether the stated number follows from the stated",
  "construction.",
  "",
  "## 1. Trait costs that do not follow from the listed construction",
  "",
  `${costs.length} across ${new Set(costs.map(cost => cost.monster)).size} monsters. "Expected" is the`,
  "cost of the construction exactly as written, per the published cost tables.",
  "",
  "| Monster | Construction as written | Stated | Expected |",
  "| --- | --- | ---: | ---: |",
  ...costs.map(cost => `| ${cost.monster} | ${cost.construction} | ${cost.stated} | ${cost.library} |`),
  "",
  "## 2. Typical Stats Dodge that does not follow from the same block",
  "",
  `${dodges.length} records. GURPS Dodge is Basic Speed + 3, plus any bonus from the creature's own`,
  "listed traits (Combat Reflexes is +1). The Computed column applies that to the Basic Speed the",
  "same Typical Stats block states. None of these creatures lists Enhanced Dodge or any other",
  "trait that would account for the gap.",
  "",
  "| Monster | Basic Speed | Trait bonus | Computed | Stated | Difference |",
  "| --- | ---: | ---: | ---: | ---: | ---: |",
  ...dodges.map(dodge => `| ${dodge.monster} | ${dodge.speed} | ${dodge.bonus >= 0 ? "+" : ""}${dodge.bonus} `
    + `| ${dodge.computed} | ${dodge.stated} | ${dodge.difference > 0 ? "+" : ""}${dodge.difference} |`),
  "",
  "Dungeons on Automatic uses the computed value in the generated GCS sheets, because a sheet has",
  "to be internally consistent to open. The package keeps the stated value, so nothing the author",
  "wrote is silently overwritten.",
  "",
];

writeFileSync(OUT_PATH, `${lines.join("\n")}\n`, "utf8");
console.log(`Wrote ${OUT_PATH}: ${costs.length} cost discrepancy(ies), ${dodges.length} dodge discrepancy(ies).`);
