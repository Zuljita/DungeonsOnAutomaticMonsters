// CER and encounter-balance audit (issue #6).
//
// The baseline CER path reads attributes, one best attack, and four traits. Every
// other mechanic — insubstantiality, possession, auras, regeneration,
// save-or-disable afflictions, spellcasting, swarm bodies, extreme mobility — is
// invisible to it by construction. This audit does not pretend otherwise. It
// states, per record, which priority mechanics the rating cannot see, and how the
// record's CER sits against its package peers, so a reviewer can judge whether
// the number is defensible rather than merely present.
//
//   node scripts/review-cer-audit.mjs                     # write review/reports/cer-audit.md
//   node scripts/review-cer-audit.mjs --format json

import { writeFileSync } from "node:fs";
import { buildReviewedPackage } from "./review/build-candidate.mjs";
import { hasUnratedDisablingAttack, mechanicLabel } from "./review/queue.mjs";

const args = process.argv.slice(2);
const format = args.includes("--format") ? args[args.indexOf("--format") + 1] : "markdown";
const outPath = args.includes("--out") ? args[args.indexOf("--out") + 1] : "review/reports/cer-audit.md";

// The rating prices exactly what the formula reads. Everything else is a
// judgement call the reviewer has to make and record. An aura or area attack is
// priced only when it was carried into the record as an auto-hit attack.
const PRICED_BY_RATING = new Set(["gaze_aura_area"]);

const { reviewed, dossiers } = buildReviewedPackage(".");
const byId = new Map(reviewed.monsters.map(record => [record.id, record]));

const rows = dossiers.map(entry => {
  const record = byId.get(entry.id);
  const effectiveness = record.effectiveness;
  const attacks = record.stats.attacks;
  const bestAttackRated = attacks.length > 0;
  const autoHitRated = attacks.some(attack => attack.autoHit === true);
  return {
    id: entry.id,
    name: entry.name,
    class: record.class,
    offenseRating: effectiveness.offenseRating,
    protectionRating: effectiveness.protectionRating,
    cer: effectiveness.combatEffectivenessRating,
    baseCer: entry.baseEffectiveness.combatEffectivenessRating,
    threatTier: effectiveness.threatTier,
    mechanics: entry.mechanics,
    unpriced: entry.mechanics.filter(id => !PRICED_BY_RATING.has(id) || (id === "gaze_aura_area" && !autoHitRated)),
    attackCount: attacks.length,
    ratedFromAttack: bestAttackRated,
    autoHitRated,
    appearing: record.encounter.averageNumberAppearing,
    wandering: record.encounter.wanderingWeight,
    hazardRated: attacks.some(attack => (attack.afflictionPoints ?? 0) > 0 || (attack.bindingSt ?? 0) > 0),
    hazardUnrated: hasUnratedDisablingAttack(record),
    hp: record.stats.attributes.hp,
    dr: record.stats.attributes.dr,
    fp: record.stats.attributes.fp,
    dodge: record.stats.attributes.dodge,
  };
});

const tiers = ["minor", "standard", "major", "severe"];
const tierStats = Object.fromEntries(tiers.map(tier => {
  const cers = rows.filter(row => row.threatTier === tier).map(row => row.cer).sort((a, b) => a - b);
  return [tier, { count: cers.length, min: cers[0] ?? null, median: median(cers), max: cers.at(-1) ?? null }];
}));

const floorRecords = rows.filter(row => row.cer <= 1);
const severeRecords = rows.filter(row => row.cer >= 100).sort((a, b) => b.cer - a.cer);
const specialRecords = rows.filter(row => row.mechanics.length > 0);
const unpricedRecords = rows.filter(row => row.unpriced.length > 0);
const missingDr = rows.filter(row => row.dr === null || row.dr === undefined);
const missingFp = rows.filter(row => row.fp === null || row.fp === undefined);
const missingDodge = rows.filter(row => row.dodge === null || row.dodge === undefined);

if (format === "json") {
  process.stdout.write(`${JSON.stringify({ tierStats, rows }, null, 2)}\n`);
} else {
  writeFileSync(outPath, renderMarkdown(), "utf8");
  console.log(
    `Wrote ${outPath}: ${rows.length} records, ${specialRecords.length} with priority mechanics, `
    + `${unpricedRecords.length} whose rating cannot see at least one of them.`,
  );
}

function renderMarkdown() {
  const lines = [
    "# CER and Encounter Balance Audit",
    "",
    "<!-- Generated by scripts/review-cer-audit.mjs. Do not edit by hand. -->",
    "",
    "Original GURPS conversion by Enraged Eggplant, from Monsters (May 11, 2024); adapted and republished with permission.",
    "",
    "## What the rating can and cannot see",
    "",
    "Offense and protection ratings are recomputed from the reviewed Typical Stats through the same code path the",
    "Dungeons on Automatic application uses (`src/modules/cer-calculator.ts`). That path reads:",
    "",
    "- offense: best attack's skill, its damage after the damage-type multiplier, the auto-hit credit for attacks",
    "  that allow no defense, ranged accuracy, FP, and Move;",
    "- the affliction term, scored **separately from the best attack**, for save-or-disable abilities;",
    "- protection: DR, the best active defense, HT, HP, and Will, plus High Pain Threshold, Recovery,",
    "  Combat Reflexes and Unfazeable.",
    "",
    "### Pricing save-or-disable abilities",
    "",
    "A petrifying gaze does no damage and is never a creature's best attack, so scoring only the best attack rated",
    "a cockatrice at the CER floor of 1. The affliction term exists for exactly this and is scored independently of",
    "the damage comparison, so an ability that removes a character from the fight counts even when it deals nothing.",
    "",
    "Each disabling construction is priced by one lever, never two:",
    "",
    "- a **Binding** (engulf, entangle, web) is priced by its ST, the term the model provides for it;",
    "- everything else is priced by the **point cost the source states for the construction**, at 1 per 5 points —",
    "  the same conversion the model already applies to durability, healing, FP-recovery, and narrow-DR traits;",
    "- an ability that costs fatigue or is cast contributes half, as the model already specifies.",
    "",
    "Point cost is used rather than the construction's enhancement percentages. Summing the percentages a GURPS",
    "gaze carries (+660% for a basilisk) produces +132 CER, which would rate a basilisk above a storm giant. The",
    "point cost is the source's own measure of how expensive the ability is, and it is stated in the document, so",
    "every score below is checkable against the source rather than derived from a rule this project invented.",
    "",
    "It still does **not** read insubstantiality, possession without a stated cost, immunities, regeneration,",
    "spellcasting, psionics, swarm bodies, or extreme mobility. Those are listed per record below rather than",
    "silently folded into a number. No record in this package is approved because the formula produced a value;",
    "each one carries the sanity check that follows in its `provenance.conversionNotes`.",
    "",
    "## Distribution",
    "",
    "| Threat tier | Records | Min CER | Median CER | Max CER |",
    "| --- | ---: | ---: | ---: | ---: |",
    ...tiers.map(tier => {
      const stats = tierStats[tier];
      return `| ${tier} | ${stats.count} | ${stats.min ?? "—"} | ${stats.median ?? "—"} | ${stats.max ?? "—"} |`;
    }),
    "",
    `Records whose ratings changed from the conversion baseline: **${rows.filter(row => row.cer !== row.baseCer).length}**.`,
    "The conversion baseline ceilinged the damage base before applying the damage-type multiplier, ignored ranged",
    "accuracy and auto-hit, and priced no save-or-disable ability at all; the reviewed values come from the",
    "consumer implementation.",
    "",
    "## Low tail — CER at the floor",
    "",
    `${floorRecords.length} record(s) sit at the CER floor of 1, meaning offense plus protection came out at or below zero.`,
    "These are genuinely feeble creatures whose rating is a floor, not a measurement.",
    "",
    "| Monster | OR | PR | Attacks | HP | Dodge | DR | Reading |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ...floorRecords.map(row =>
      `| ${row.name} | ${row.offenseRating} | ${row.protectionRating} | ${row.attackCount} | ${row.hp ?? "—"} `
      + `| ${row.dodge ?? "—"} | ${row.dr ?? "—"} | ${floorReading(row)} |`),
    "",
    "## High tail — CER 100 and above",
    "",
    "| Monster | CER | OR | PR | Tier | Appearing | Unpriced mechanics |",
    "| --- | ---: | ---: | ---: | --- | ---: | --- |",
    ...severeRecords.map(row =>
      `| ${row.name} | ${row.cer} | ${row.offenseRating} | ${row.protectionRating} | ${row.threatTier} `
      + `| ${row.appearing} | ${row.unpriced.map(mechanicLabel).join("; ") || "—"} |`),
    "",
    "The Tarrasque anchors the top of the package at CER "
      + `${rows.find(row => row.name === "Tarrasque")?.cer ?? "—"}. `
      + "That is not an artefact: it carries the highest HP, DR and damage in the corpus and the rating tracks them",
    "directly. It is roughly twice the next-highest record, which is the correct shape for a capstone monster.",
    "",
    "## Data gaps that suppress ratings",
    "",
    "These are stated policy, not parse accidents; see",
    "[`../policy/cer-scope-policy.md`](../policy/cer-scope-policy.md) (issue #17).",
    "",
    `- **${missingDr.length}** records have no parsed DR. Their sources state DR as \"-\" or as a conditional value`,
    "  (\"20 vs. cold and fire\"). Policy: the uniform-DR slot scores only unconditional DR, so these score its",
    "  unconditional portion — usually zero — and their protection rating is a deliberate floor. Weighting the",
    "  conditional value would require an attack-mix assumption the package refuses to invent; the record's traits",
    "  carry the conditional construction verbatim for the GM to read.",
    `- **${missingFp.length}** records have no parsed FP (source states N/A — creatures outside the fatigue economy).`,
    "  Policy: scored at the FP baseline, contributing 0 — neither penalised for the missing number nor credited",
    "  for tirelessness.",
    `- **${missingDodge.length}** record(s) have no parsed Dodge (source states N/A), scored as no active defense.`,
    "",
    "## Priority mechanics the rating cannot price",
    "",
    `${unpricedRecords.length} of ${rows.length} records carry at least one priority mechanic that the rating does not read.`,
    "",
    "Each family's disposition — priced with a stated lever, or out of scope with the reason — is recorded in",
    "[`../policy/cer-scope-policy.md`](../policy/cer-scope-policy.md) (issue #15). A GM should read a listed",
    "mechanic as \"this creature is harder than its number\": the threat tier of a record in this table is a floor,",
    "not a measurement.",
    "",
    "| Monster | CER | Tier | Peer median (tier) | Mechanics the rating cannot see |",
    "| --- | ---: | --- | ---: | --- |",
    ...unpricedRecords
      .sort((a, b) => b.cer - a.cer)
      .map(row =>
        `| ${row.name} | ${row.cer} | ${row.threatTier} | ${tierStats[row.threatTier].median} `
        + `| ${row.unpriced.map(mechanicLabel).join("; ")} |`),
    "",
    "## Encounter metadata",
    "",
    "Appearing counts and wandering weights are derived from the reviewed threat tier and creature class; the",
    "source states neither. The rule is recorded on every record.",
    "",
    `${rows.filter(row => row.hazardRated).length} record(s) carry a save-or-disable ability the rating now prices.`,
    `A further ${rows.filter(row => row.hazardUnrated).length} carry one it still cannot — the source states no point`,
    "cost or Binding ST to score them by — and those keep their appearing count capped at two, because the rating",
    "understates how dangerous a group of them is. Distribution:",
    "",
    "| Appearing | Wandering weight | Records |",
    "| ---: | ---: | ---: |",
    ...encounterDistribution().map(([appearing, wandering, count]) => `| ${appearing} | ${wandering} | ${count} |`),
    "",
  ];
  return `${lines.join("\n")}\n`;
}

function floorReading(row) {
  if (row.attackCount === 0) return "no attack in the source";
  if (row.offenseRating <= 0 && row.protectionRating <= 0) return "feeble on both axes; floor is correct";
  if (row.protectionRating <= 0) return "no meaningful defense; floor is correct";
  return "offense below baseline; floor is correct";
}

function encounterDistribution() {
  const counts = new Map();
  for (const row of rows) {
    const key = `${row.appearing}|${row.wandering}`;
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  return [...counts.entries()]
    .map(([key, count]) => [...key.split("|").map(Number), count])
    .sort((a, b) => a[0] - b[0] || a[1] - b[1]);
}

function median(values) {
  if (values.length === 0) return null;
  const middle = Math.floor(values.length / 2);
  return values.length % 2 === 0 ? Math.round((values[middle - 1] + values[middle]) / 2) : values[middle];
}
