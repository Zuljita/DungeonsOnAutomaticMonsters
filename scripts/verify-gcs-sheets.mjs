// Have GCS check the generated sheets against the reviewed package.
//
//   node scripts/verify-gcs-sheets.mjs
//   node scripts/verify-gcs-sheets.mjs --report
//
// The sheets state a construction; the package states what that construction is
// supposed to produce. Only GCS can evaluate the first, so this converts a copy
// of every sheet and compares GCS's own computed values against the package.
// A disagreement means the ancestry, the individual adjustments, or the package
// drifted apart — the kind of break that is otherwise invisible until someone
// opens a sheet and finds a Balor with the wrong DX.
//
// Requires a GCS install (see scripts/gcs-cli.mjs). It is a separate command
// from `npm test` for that reason.

import { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { REVIEWED_PATH } from "./review/build-candidate.mjs";
import { GcsUnavailableError, convertInPlace } from "./gcs-cli.mjs";

const SHEET_DIR = "converted/enraged-eggplant/gcs-sheets";
const REPORT_PATH = "review/reports/gcs-verification.md";

/** package attribute -> the GCS attribute holding the same quantity */
const COMPARED = {
  st: "st", dx: "dx", iq: "iq", ht: "ht",
  will: "will", per: "per", hp: "hp", fp: "fp",
  speed: "basic_speed",
};

const report = process.argv.includes("--report");
const pkg = JSON.parse(readFileSync(REVIEWED_PATH, "utf8"));

let scratch;
try {
  scratch = mkdtempSync(join(tmpdir(), "doa-gcs-verify-"));
  cpSync(SHEET_DIR, scratch, { recursive: true });
  convertInPlace(scratch);
} catch (error) {
  if (error instanceof GcsUnavailableError) {
    console.error(`${error.message}\nGCS verification skipped — this check cannot run without it.`);
    process.exit(2);
  }
  throw error;
}

const failures = [];
let compared = 0;
let dodgeChecked = 0;
let dodgeMatched = 0;

for (const record of pkg.monsters) {
  const resolved = JSON.parse(readFileSync(join(scratch, `${record.id}.gcs`), "utf8"));
  const valueOf = id => resolved.attributes.find(entry => entry.attr_id === id)?.calc?.value;
  const want = record.stats?.attributes ?? {};

  for (const [key, attribute] of Object.entries(COMPARED)) {
    // A null in the package is "the source states none", not "zero". Nothing to check.
    if (want[key] == null) continue;
    compared += 1;
    const got = valueOf(attribute);
    if (Number(got) !== Number(want[key])) {
      failures.push(`${record.name} (${record.id}): ${key} — package ${want[key]}, GCS ${got}`);
    }
  }
  if (want.dodge != null) {
    dodgeChecked += 1;
    if (Number(resolved.calc?.dodge?.[0]) === Number(want.dodge)) dodgeMatched += 1;
  }
}

rmSync(scratch, { recursive: true, force: true });

if (report) {
  const lines = [
    "# GCS Sheet Verification",
    "",
    "<!-- Generated by scripts/verify-gcs-sheets.mjs. Do not edit by hand. -->",
    "",
    "Every generated `.gcs` sheet converted by the GCS desktop application, with GCS's own computed",
    "values compared against the reviewed package's Typical Stats.",
    "",
    `- records: ${pkg.monsters.length}`,
    `- attribute values compared: ${compared}`,
    `- disagreements: ${failures.length}`,
    `- dodge matching the package: ${dodgeMatched}/${dodgeChecked}`,
    "",
  ];
  if (failures.length > 0) {
    lines.push("## Disagreements", "", ...failures.map(failure => `- ${failure}`), "");
  }
  writeFileSync(REPORT_PATH, `${lines.join("\n")}\n`, "utf8");
  console.log(`Wrote ${REPORT_PATH}.`);
}

if (failures.length > 0) {
  console.error(`GCS verification failed on ${failures.length} value(s):`);
  for (const failure of failures.slice(0, 20)) console.error(`  - ${failure}`);
  if (failures.length > 20) console.error(`  ... and ${failures.length - 20} more`);
  process.exit(1);
}
console.log(
  `GCS verification passed: ${compared} attribute value(s) across ${pkg.monsters.length} record(s) agree. `
  + `Dodge matches on ${dodgeMatched}/${dodgeChecked}.`,
);
